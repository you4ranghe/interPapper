insert into public.books (title, introduction, author_note, cover_path, book_type, published_year, created_at)
select
  t.title,
  t.introduction,
  E'늘 같은 자리에서 같은 시간에 펜을 들었습니다. 그 반복이 책 한 권이 되었습니다.\n\n— 저자 드림' as author_note,
  case (t.idx % 3)
    when 0 then '/covers/book1.svg'
    when 1 then '/covers/book2.svg'
    else        '/covers/book3.svg'
  end as cover_path,
  case (t.idx % 4)
    when 0 then '산문'
    when 1 then '에세이'
    when 2 then '회고'
    else        '소설'
  end as book_type,
  2020 + (t.idx % 6) as published_year,
